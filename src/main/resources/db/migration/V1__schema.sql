CREATE TABLE app_user (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, email VARCHAR(150) NOT NULL UNIQUE,
 password VARCHAR(100) NOT NULL, dni VARCHAR(8) NOT NULL UNIQUE, phone VARCHAR(20) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK(role IN ('CLIENTE','RECEPCION','VETERINARIO','ADMIN')),
 active BOOLEAN NOT NULL DEFAULT TRUE, failed_attempts INT NOT NULL DEFAULT 0,
 locked_until TIMESTAMP, consent BOOLEAN NOT NULL DEFAULT FALSE);
CREATE TABLE pet (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_id BIGINT NOT NULL REFERENCES app_user(id), name VARCHAR(80) NOT NULL,
 species VARCHAR(40) NOT NULL, breed VARCHAR(80) NOT NULL DEFAULT '', birth_date DATE);
CREATE TABLE clinical_service (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(80) NOT NULL UNIQUE, active BOOLEAN NOT NULL DEFAULT TRUE);
CREATE TABLE business_hours (day_of_week INT PRIMARY KEY CHECK(day_of_week BETWEEN 1 AND 7),
 opening TIME NOT NULL, closing TIME NOT NULL, active BOOLEAN NOT NULL, CHECK(opening<closing));
CREATE TABLE holiday (holiday_date DATE PRIMARY KEY, description VARCHAR(120) NOT NULL);
CREATE TABLE appointment (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pet_id BIGINT NOT NULL REFERENCES pet(id), vet_id BIGINT NOT NULL REFERENCES app_user(id),
 service_id BIGINT NOT NULL REFERENCES clinical_service(id), starts_at TIMESTAMP NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN ('RESERVADA','EN_ESPERA','ATENDIDA','CANCELADA','NO_ASISTIO')),
 reschedules INT NOT NULL DEFAULT 0 CHECK(reschedules BETWEEN 0 AND 2),
 created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL);
CREATE INDEX appointment_vet_time ON appointment(vet_id,starts_at);
CREATE INDEX appointment_pet_time ON appointment(pet_id,starts_at);
CREATE TABLE clinical_record (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 appointment_id BIGINT NOT NULL UNIQUE REFERENCES appointment(id), reason VARCHAR(1000) NOT NULL,
 diagnosis VARCHAR(2000) NOT NULL, treatment VARCHAR(2000) NOT NULL,
 weight DECIMAL(6,2) NOT NULL CHECK(weight>0 AND weight<=500), created_at TIMESTAMP NOT NULL);
CREATE TABLE audit_event (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT REFERENCES app_user(id), action VARCHAR(100) NOT NULL,
 entity_id BIGINT, created_at TIMESTAMP NOT NULL);
CREATE TABLE theme_setting (setting_key VARCHAR(40) PRIMARY KEY, setting_value VARCHAR(100) NOT NULL);
